public class EscopoRenomeacao {
    public static void main(String[] args) {
        int n = 2;
        while (n > 0) {
            int i = n * 10;
            System.out.println(i);
            n--;
        }
        int i = 5;
        System.out.println(i);
        int m = 1;
        while (m > 0) {
            int t = 1;
            while (t > 0) {
                int x = 7;
                System.out.println(x);
                t--;
            }
            m--;
        }
        int x = 9;
        int t = 8;
        System.out.println(x + t);
    }
}
