public class StringsEscapes {
    public static void main(String[] args) {
        System.out.println("aspas \" e barra \\ ok");
        System.out.println("tab\tfim");
        System.out.println("");
        char a = '"';
        char b = '\\';
        System.out.println(a);
        System.out.println(b);
        System.out.println("{chaves} sem args");
        System.out.println("100%");
    }
}
