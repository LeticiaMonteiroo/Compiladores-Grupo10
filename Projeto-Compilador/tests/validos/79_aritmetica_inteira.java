public class AritmeticaInteira {
    public static void main(String[] args) {
        int a = 17;
        int b = 5;
        System.out.println(a / b);
        System.out.println(a % b);
        System.out.println(-a / b);
        System.out.println(-a % b);
        System.out.println(a * b + a / b - a % b);
        System.out.println(2 + 3 * 4);
        System.out.println((2 + 3) * 4);
        System.out.println(100 / 10 / 5);
        System.out.println(100 / (10 / 5));
        System.out.println(100 - 10 - 5);
        System.out.println(100 - (10 - 5));
        char c = 'a';
        System.out.println("x" + c + 1);
    }
}
